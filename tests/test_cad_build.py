class TestShapedObjects(unittest.TestCase):
    """`Shape` does not always hold a shape, and one exception lost a document."""

    def test_a_shape_property_that_links_to_an_object_is_skipped(self):
        """A FEM mesh points `Shape` at the part it was meshed from.

        The link is a document object, so every shape method on it raises. That
        happened inside the generator, where the caller's per-object `except`
        could not catch it, and the whole document went unmeasured.
        """
        pad = _Object("Pad", "PartDesign::Pad", shape=_Shape(centre_of_mass=(1.0, 2.0, 3.0)))
        mesh = _Object("FEMMeshNetgen", "Fem::FemMeshShapeNetgenObject", shape=pad)
        measured = list(cad_fingerprint._shaped_objects(
            _Document([pad, mesh]), cad_fingerprint.cad_rules))
        self.assertEqual([obj.Name for obj, _ in measured], ["Pad"])

    def test_a_document_of_one_fem_mesh_still_measures_its_geometry(self):
        """The regression that mattered: one mesh must not cost every object."""
        shapes = [
            _Object(f"Pad{index}", "PartDesign::Pad", shape=_Shape(centre_of_mass=(0.0, 0.0, 0.0)))
            for index in range(3)
        ]
        mesh = _Object("FEMMeshGmsh", "Fem::FemMeshShapeBaseObjectPython", shape=shapes[0])
        measured = list(cad_fingerprint._shaped_objects(
            _Document([mesh, *shapes]), cad_fingerprint.cad_rules))
        self.assertEqual(len(measured), 3)

    def test_an_object_with_no_shape_at_all_is_skipped(self):
        spreadsheet = _Object("Params", "Spreadsheet::Sheet")
        measured = list(cad_fingerprint._shaped_objects(
            _Document([spreadsheet]), cad_fingerprint.cad_rules))
        self.assertEqual(measured, [])


class _ViewObject:
    def __init__(self):
        self.Visibility = False


class _TreeObject:
    """A FreeCAD object with a type, a label and, for containers, a Group.

    It starts hidden, which is how a new part opened after a headless build.
    """

    def __init__(self, doc, type_id, name):
        self.TypeId = type_id
        self.Name = name
        self.Label = name
        self.Group = []
        self.Visibility = False
        self.ViewObject = _ViewObject() if doc.gui else None
        self.Placement = types.SimpleNamespace(Rotation=None)
        self.expressions = {}
        self._doc = doc

    def setExpression(self, path, expr):
        self.expressions[path] = expr

    def addObject(self, obj):
        # FreeCAD moves the object out of any other group it was in.
        for other in self._doc.Objects:
            if obj in other.Group:
                other.Group.remove(obj)
        self.Group.append(obj)


#: FreeCAD gives each of these its own coordinate system when it is created.
_HAS_ORIGIN = ("App::Part", "PartDesign::Body", "Assembly::AssemblyObject")
_ORIGIN_FEATURES = (
    ("App::Line", "X_Axis"), ("App::Line", "Y_Axis"), ("App::Line", "Z_Axis"),
    ("App::Plane", "XY_Plane"), ("App::Plane", "XZ_Plane"),
    ("App::Plane", "YZ_Plane"), ("App::Point", "Origin_Point"),
)


class _TreeDocument:
    def __init__(self, file_name="/m/rail/cad/rail.FCStd", gui=False):
        self.Name = "rail"
        self.FileName = file_name
        self.Objects = []
        self.journal = []
        self.gui = gui

    def addObject(self, type_id, name):
        obj = self._add(type_id, name)
        if type_id == cad_rules.FRAME_TYPE:
            # A frame owns its axes and planes directly. They start hidden
            # here, so a test proves that the build shows them.
            obj.OriginFeatures = [self._add(t, n) for t, n in _ORIGIN_FEATURES]
        if type_id in _HAS_ORIGIN:
            # The origin starts visible here, so a test proves that the build
            # hides it and does not only leave it as it was.
            origin = self._add("App::Origin", "Origin")
            origin.OriginFeatures = [self._add(t, n) for t, n in _ORIGIN_FEATURES]
            for item in [origin, *origin.OriginFeatures]:
                item.Visibility = True
            obj.Origin = origin
        return obj

    def _add(self, type_id, name):
        taken = {o.Name for o in self.Objects}
        unique, n = name, 0
        while unique in taken:
            n += 1
            unique = f"{name}{n:03d}"
        obj = _TreeObject(self, type_id, unique)
        self.Objects.append(obj)
        return obj

    def shapes(self):
        """The objects that are not part of a coordinate system."""
        return [o for o in self.Objects if o.TypeId not in cad_rules.ORIGIN_TYPES]

    def origins(self):
        return [o for o in self.Objects if o.TypeId in cad_rules.ORIGIN_TYPES]

    def getObjectsByLabel(self, label):
        return [o for o in self.Objects if o.Label == label]

    def openTransaction(self, name):
        self.journal.append("open")

    def commitTransaction(self):
        self.journal.append("commit")

    def abortTransaction(self):
        self.journal.append("abort")

    def recompute(self):
        pass

    def save(self):
        self.journal.append("save")


