class TestNewObjectsAreVisible(unittest.TestCase):
    """A new part or assembly opens visible; its coordinate system stays hidden."""

    def _run(self, build_fn, doc):
        with mock.patch.object(cad_build, "open_document", return_value=(doc, False)), \
                mock.patch.object(cad_build.cad_fingerprint, "read_params", return_value={}), \
                mock.patch.object(cad_build.cad_fingerprint, "write"):
            cad_build.run(build_fn)

    def test_body_shows_the_part_and_the_body(self):
        doc = _TreeDocument()
        b = cad_build.body(doc)
        self.assertTrue(cad_build.part(doc).Visibility)
        self.assertTrue(b.Visibility)
        self.assertEqual(len(doc.origins()), 16)
        self.assertFalse(any(o.Visibility for o in doc.origins()))

    def test_gui_view_is_set_too(self):
        doc = _TreeDocument(gui=True)
        b = cad_build.body(doc)
        self.assertTrue(b.ViewObject.Visibility)
        self.assertFalse(b.Origin.ViewObject.Visibility)

    def test_run_shows_an_assembly_its_links_and_the_body_tip(self):
        doc = _TreeDocument("/m/x-axis/cad/assemblies/x-axis.FCStd")

        def build(d, params):
            d.addObject("Assembly::AssemblyObject", "Assembly")
            d.addObject("App::Link", "Rail")
            master = d.addObject("PartDesign::Body", "Body_master")
            master.Tip = d.addObject("PartDesign::Pad", "Pad")
            d.addObject("Sketcher::SketchObject", "Sketch")

        self._run(build, doc)
        shown = {o.Name for o in doc.shapes() if o.Visibility}
        self.assertEqual(shown, {"Assembly", "Rail", "Body_master", "Pad"})
        self.assertEqual(len(doc.origins()), 16)
        self.assertFalse(any(o.Visibility for o in doc.origins()))

    def test_an_object_hidden_before_the_build_stays_hidden(self):
        doc = _TreeDocument()
        b = cad_build.body(doc)
        b.Visibility = False
        self._run(lambda d, p: cad_build.body(d), doc)
        self.assertFalse(b.Visibility)

    def test_a_new_frame_shows_with_its_axes(self):
        doc = _TreeDocument()
        f = cad_build.frame(doc, "IF_mount")
        self.assertTrue(f.Visibility)
        self.assertEqual(len(f.OriginFeatures), 7)
        self.assertTrue(all(o.Visibility for o in f.OriginFeatures))
        # The Part container's own coordinate system stays hidden.
        self.assertFalse(cad_build.part(doc).Origin.Visibility)

    def test_run_shows_an_imported_solid_and_a_frame_but_not_the_origin(self):
        doc = _TreeDocument()

        def build(d, params):
            container = cad_build.part(d)
            container.addObject(d.addObject("Part::Feature", "Part__Feature"))
            cad_build.frame(d, "IF_rail", container=container)

        self._run(build, doc)
        by_name = {o.Name: o for o in doc.Objects}
        self.assertTrue(by_name["Part__Feature"].Visibility)
        self.assertTrue(by_name["Frame"].Visibility)
        self.assertTrue(all(o.Visibility for o in by_name["Frame"].OriginFeatures))
        self.assertFalse(by_name["Origin"].Visibility)
        self.assertFalse(any(o.Visibility for o in by_name["Origin"].OriginFeatures))

    def test_a_frame_a_person_hid_stays_hidden_on_a_rerun(self):
        doc = _TreeDocument()
        f = cad_build.frame(doc, "IF_mount")
        f.Visibility = False
        self._run(lambda d, p: cad_build.frame(d, "IF_mount"), doc)
        self.assertFalse(f.Visibility)


class TestRunChecksTheTree(unittest.TestCase):
    """run() undoes a build that leaves a Body on top, and saves nothing."""

    def _run(self, build_fn):
        doc = _TreeDocument()
        with mock.patch.object(cad_build, "open_document", return_value=(doc, False)), \
                mock.patch.object(cad_build.cad_fingerprint, "read_params", return_value={}), \
                mock.patch.object(cad_build.cad_fingerprint, "write"):
            try:
                cad_build.run(build_fn)
            except RuntimeError as err:
                return doc, err
        return doc, None

    def test_body_on_top_aborts_the_transaction(self):
        doc, err = self._run(lambda d, p: d.addObject("PartDesign::Body", "Body"))
        self.assertIn("not inside a Part container", str(err))
        self.assertEqual(doc.journal, ["open", "abort"])

    def test_body_inside_a_part_commits_and_saves(self):
        doc, err = self._run(lambda d, p: cad_build.body(d))
        self.assertIsNone(err)
        self.assertEqual(doc.journal, ["open", "commit", "save"])


