class TestReadParams(unittest.TestCase):
    def setUp(self):
        self._tmp = Path(tempfile.mkdtemp(prefix="doqs-cad-"))
        self.cad = self._tmp / "cad"
        self.cad.mkdir()

    def _write(self, text: str) -> None:
        (self.cad / "params.csv").write_text(text, encoding="utf-8")

    def test_missing_file_is_empty(self):
        self.assertEqual(cad_fingerprint.read_params(self.cad), {})

    def test_skips_generated_header_and_floats_values(self):
        self._write(
            "# generated by resolve_params.py — do not edit\n"
            "alias,value,unit,description\n"
            "rail_length,500,mm,Rail\n"
            "finish,anodised,,Surface\n"
        )
        self.assertEqual(
            cad_fingerprint.read_params(self.cad),
            {"rail_length": 500.0, "finish": "anodised"},
        )

    def test_blank_alias_rows_are_ignored(self):
        self._write("alias,value,unit,description\n,,,\nbore,8,mm,Bore\n")
        self.assertEqual(cad_fingerprint.read_params(self.cad), {"bore": 8.0})

    def test_header_without_required_columns_is_empty(self):
        self._write("name,amount\nrail_length,500\n")
        self.assertEqual(cad_fingerprint.read_params(self.cad), {})

    def test_explicit_path_wins_over_cad_dir(self):
        other = self._tmp / "elsewhere.csv"
        other.write_text("alias,value\nbore,3\n", encoding="utf-8")
        self.assertEqual(
            cad_fingerprint.read_params(self.cad, path=other), {"bore": 3.0}
        )


